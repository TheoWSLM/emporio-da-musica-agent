"""Replays scripted conversations against the real agent and writes them as Markdown transcripts."""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict

from emporio.config import Settings
from emporio.container import Container


class Script(BaseModel):
    model_config = ConfigDict(extra="forbid")

    file: str
    title: str
    summary: str
    turns: list[str]
    reference_date: date | None = None


def _backstage(events: list[dict[str, Any]]) -> list[str]:
    lines: list[str] = []
    classification = next((e for e in events if e["type"] == "classification"), None)
    if classification:
        a = classification["assessment"]
        lines.append(
            f"classifier `{classification['provider']}` ({classification['latency_ms']} ms): route **{classification['route']}**, "
            f"intent `{a['intent']}`, scope `{a['scope']}`, threat `{a['threat']}`"
        )
    for tool in (e for e in events if e["type"] == "tool"):
        args = ", ".join(f"{k}={v!r}" for k, v in tool["arguments"].items() if v is not None)
        lines.append(f"tool `{tool['name']}({args})` — {tool['duration_ms']} ms")
    message = next((e for e in events if e["type"] == "message"), None)
    if message and message["reply"]["cited_sections"]:
        lines.append("policy cited: " + "; ".join(message["reply"]["cited_sections"]))
    done = next((e for e in events if e["type"] == "done"), None)
    if done:
        lines.append(
            f"outcome `{done['outcome']}` · {done['latency_ms'] / 1000:.1f} s · {done['model_rounds']} agent call(s)"
        )
    return lines


async def run_examples(settings: Settings, scripts_path: Path, output_dir: Path) -> list[Path]:
    scripts = [
        Script.model_validate(raw)
        for raw in yaml.safe_load(scripts_path.read_text(encoding="utf-8"))
    ]
    output_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for script in scripts:
        container = Container.build(
            settings.model_copy(update={"app_reference_date": script.reference_date})
        )
        try:
            conversation_id = await container.conversations.create("example")
            body: list[str] = []
            for turn in script.turns:
                events = [
                    event async for event in container.assistant.stream(conversation_id, turn)
                ]
                message = next(e for e in events if e["type"] == "message")
                reply = message["reply"]["message"].replace("\n", "\n> ")
                body += [f"**Cliente:** {turn}", "", f"> **Lia:** {reply}", ""]
                body += ["<details><summary>Bastidores</summary>", ""]
                body += [f"- {line}" for line in _backstage(events)]
                body += ["", "</details>", ""]
            provider = "jev" if container.settings.jev_enabled else "openai"
            header = [
                f"# {script.title}",
                "",
                f"**Summary (EN):** {script.summary}",
                "",
                f"_Generated by `make examples` with agent `{settings.agent_model}`, classifier `{provider}`"
                + (
                    f", business date pinned to {script.reference_date:%Y-%m-%d}"
                    if script.reference_date
                    else ""
                )
                + "._",
                "",
                "---",
                "",
            ]
            path = output_dir / script.file
            path.write_text("\n".join(header + body), encoding="utf-8")
            written.append(path)
        finally:
            await container.close()
    return written
